"""
config/week_utils.py

트리거 시점과 무관하게, "리포트 대상 주간"의 범위를 일관되게 계산합니다.

트리거 스케줄 (2026-07-21 확정): 매주 월요일 오전 11시 + 매주 화요일 오전 11시
(스프린트 넘버 + ad_account_id로 구분되어, 화요일 실행분이 최신본으로 남게 됨 —
 사실상 매주 화요일 실행 결과 1건만 최종적으로 남는 구조)

# ── 이전 계획 (폐기, 참고용으로 주석 처리만 하고 삭제하지 않음) ──
# 초기에는 3가지 트리거(월요일 10시 / 월요일 13시 / "초안 생성" 버튼 수동 클릭)를
# 고려했으나, 수동 트리거(버튼)는 없애기로 결정. 월요일 11시 + 화요일 11시,
# 2개의 자동 트리거만 운영하는 것으로 확정됨.
# ────────────────────────────────────────────────

핵심 전제 (업무 사이클): 콘텐츠 게시(N주) → 광고 집행(N+1주) → 리포트 작성(N+2주)
즉 트리거가 실행되는 시점에 다뤄야 할 데이터는 "이번 주"가 아니라
"지난 주(캠페인이 집행됐던 주간)"입니다.

또한 실제 캠페인은 "월요일 11시~15시 시작 → 그 다음 주 월요일 11시~15시까지"
운영되어, 캘린더 기준 일요일 24시에 딱 끊으면 월요일 오전 시간대의 성과가
누락됩니다. 이를 보완하기 위해 week_end는 "그 주 일요일 고정"이 아니라
"코드 실행일 - 1일(어제)"로 계산합니다. DB가 매일 오전 9시에 전날 데이터를
적재하므로, 실행일 당일 데이터는 아직 존재하지 않아 반드시 "어제까지"만
조회 가능합니다.

로직:
1. 오늘이 속한 주의 월요일을 구함 (오늘이 월요일이면 오늘 그대로,
   아니면 가장 가까운 과거 월요일)
2. 거기서 7일을 더 빼서 "지난 주 월요일"을 week_start로 삼음
   (월/화 어느 요일에 실행되든 같은 값이 나옴 — 같은 주 안에서는 불변)
3. week_end = 실행일(오늘) - 1일 (어제, 실행 요일에 따라 매번 달라짐)

예시 (7/20 월요일, 7/21 화요일 실행):
    7/20(월) 실행 -> week_start=7/13, week_end=7/19 (어제)
    7/21(화) 실행 -> week_start=7/13(동일), week_end=7/20 (어제, 하루 더 포함됨)
"""

from datetime import date, timedelta


def get_report_week_range(today: date = None) -> tuple:
    """
    오늘 날짜를 기준으로, 리포트 대상이 되는 "지난 주" 범위를 계산합니다.
    week_start는 지난 주 월요일로 고정, week_end는 실행일 기준 어제까지로
    매번 달라집니다 (월요일 실행보다 화요일 실행이 하루 더 포함됨).

    Args:
        today: 기준 날짜 (생략하면 실제 오늘 날짜 사용, 테스트 시 지정 가능)

    Returns:
        tuple: (week_start, week_end) - 둘 다 'YYYY-MM-DD' 문자열
    """
    if today is None:
        today = date.today()

    # date.weekday(): 월요일=0, 화요일=1, ..., 일요일=6
    days_since_monday = today.weekday()
    this_week_monday = today - timedelta(days=days_since_monday)

    week_start = this_week_monday - timedelta(days=7)  # 지난 주 월요일 (고정)
    week_end = today - timedelta(days=1)                # 실행일 기준 어제 (가변)

    return week_start.strftime("%Y-%m-%d"), week_end.strftime("%Y-%m-%d")
