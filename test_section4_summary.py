# ------------------------------------------------------------
# 사후 검증: 요약문에 원문에 없는 콘텐츠명·숫자가 등장했는지 기계적으로 확인
# ------------------------------------------------------------

_CONTENT_CODE_PATTERN = re.compile(r"S?\d{2,3}-\d+|S\d{2,3}")
_NUMBER_PATTERN = re.compile(r"\d+(?:\.\d+)?%|\d+명|\d+주|\d+회")


def _extract_facts(text: str) -> dict:
    return {
        "content_codes": set(_CONTENT_CODE_PATTERN.findall(text)),
        "numbers": set(_NUMBER_PATTERN.findall(text)),
    }


def check_grounding(original: str, summary: str) -> dict:
    """
    요약문에 원문에 없는 콘텐츠명·숫자가 새로 등장했는지 확인합니다.
    (AI가 요약 과정에서 사실을 지어냈을 가능성을 기계적으로 점검하는 용도)
    """
    original_facts = _extract_facts(original)
    summary_facts = _extract_facts(summary)

    new_content_codes = summary_facts["content_codes"] - original_facts["content_codes"]
    new_numbers = summary_facts["numbers"] - original_facts["numbers"]

    return {
        "새로_등장한_콘텐츠명": sorted(new_content_codes),
        "새로_등장한_숫자": sorted(new_numbers),
    }


