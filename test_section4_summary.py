        if not grounding["새로_등장한_콘텐츠명"] and not grounding["새로_등장한_숫자"]:
            print("✅ 원문 근거 밖의 콘텐츠명·숫자 없음")
        else:
            print(f"⚠️ 새로 등장한 콘텐츠명: {grounding['새로_등장한_콘텐츠명']}")
            print(f"⚠️ 새로 등장한 숫자: {grounding['새로_등장한_숫자']}")
