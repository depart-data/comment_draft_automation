def build_summary_prompt(text: str) -> str:
    """
    단일 주차 섹션4 원문 하나만을 요약하는 프롬프트를 만듭니다.
    다른 주차 내용과 섞지 않고, 이 원문 안의 내용만으로 요약합니다.

    ※ 프롬프트 지시문 전면 개편 중 — 아래 return문 안을 자유롭게 채워 넣으세요.
       {text} 자리에 원문이 그대로 삽입됩니다 (f-string).
    """
